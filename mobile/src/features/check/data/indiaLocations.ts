export const ALL_INDIAN_STATES: string[] = ALL_INDIAN_STATE_LOCATIONS.map((s) => s.name);

export function getDistrictsForState(stateName: string): string[] {
  const match = ALL_INDIAN_STATE_LOCATIONS.find(
    (s) => s.name.toLowerCase() === (stateName || '').toLowerCase()
  );
  if (match && match.districts.length > 0) {
    return match.districts;
  }
  // Default fallback for unspecified state
  return ['Central District', 'North District', 'South District', 'East District', 'West District'];
}

